"""Generate a policy corpus and a labelled invoice set. No model calls.

    uv run python scripts/generate_dataset.py --invoices 150

Writes:
    evals/fixtures/corpus/*.md          the policy documents, with distractors
    evals/fixtures/generated/*.md       the invoices
    evals/decisions-train.jsonl         tune against this
    evals/decisions-holdout.jsonl       score once, at the end
    evals/decisions-generated.jsonl     both, for a single full run

**The split is the point.** Tuning against every case and then reporting on
every case measures how well the change was fitted to the cases you were
staring at. The holdout is not looked at while iterating; it is what tells
you afterwards whether the improvement was real. Split by scenario so both
halves carry the same mix of nasties rather than the rare ones landing
entirely on one side.

Free and deterministic: same seed, same corpus, every time. Nothing here
calls a model, so regenerating costs nothing and an eval set that is cheap
to rebuild is one that actually gets rebuilt.

Running the eval over the result is the part that costs money: roughly three
model calls per invoice per pass. Generate freely; run deliberately.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from evals.factories import build_corpus, build_invoices  # noqa: E402

FIXTURES = Path(__file__).resolve().parents[1] / "evals/fixtures"
CORPUS_DIR = FIXTURES / "corpus"
INVOICE_DIR = FIXTURES / "generated"
EVALS = Path(__file__).resolve().parents[1] / "evals"
DATASET = EVALS / "decisions-generated.jsonl"
TRAIN = EVALS / "decisions-train.jsonl"
HOLDOUT = EVALS / "decisions-holdout.jsonl"


def _write(path: Path, cases: list, note: str) -> None:
    with path.open("w", encoding="utf-8") as handle:
        handle.write(
            f"# {note}. Generated by scripts/generate_dataset.py.\n"
            "# Labels are not derived from the documents: each invoice was\n"
            "# synthesized FROM its label, so the ground truth is exact rather\n"
            "# than somebody's reading of it.\n"
        )
        for invoice in cases:
            handle.write(
                json.dumps(
                    {
                        "document": f"generated/{invoice.filename}",
                        "expected": invoice.scenario.expected,
                        "must_cite_dimensions": list(invoice.scenario.dimensions),
                        "note": invoice.scenario.note,
                    }
                )
                + "\n"
            )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--invoices", type=int, default=150)
    parser.add_argument("--corpus-seed", type=int, default=7)
    parser.add_argument("--invoice-seed", type=int, default=11)
    parser.add_argument(
        "--holdout",
        type=float,
        default=1 / 3,
        help="share reserved for the held-out set (default one third)",
    )
    parser.add_argument(
        "--clean", action="store_true", help="delete previously generated files first"
    )
    args = parser.parse_args()

    if args.clean:
        for directory in (CORPUS_DIR, INVOICE_DIR):
            shutil.rmtree(directory, ignore_errors=True)

    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    INVOICE_DIR.mkdir(parents=True, exist_ok=True)

    corpus = build_corpus(seed=args.corpus_seed)
    for name, text in corpus.items():
        (CORPUS_DIR / name).write_text(text, encoding="utf-8")
    clauses = sum(text.count("\n#") for text in corpus.values())
    print(f"corpus: {len(corpus)} documents, ~{clauses} clauses -> {CORPUS_DIR.name}/")
    for name in corpus:
        marker = "  (distractor)" if name != "procurement-policy.md" else "  (governs invoices)"
        print(f"  {name}{marker}")

    invoices = build_invoices(args.invoices, seed=args.invoice_seed)
    for invoice in invoices:
        (INVOICE_DIR / invoice.filename).write_text(invoice.markdown, encoding="utf-8")

    # Split by scenario, so both halves carry the same mix. A random split
    # puts all four illegal-VAT cases on one side often enough to matter.
    by_scenario: dict[str, list] = {}
    for invoice in invoices:
        by_scenario.setdefault(invoice.scenario.key, []).append(invoice)

    train, holdout = [], []
    for cases in by_scenario.values():
        cut = round(len(cases) * (1 - args.holdout))
        train.extend(cases[:cut])
        holdout.extend(cases[cut:])

    for path, cases, note in (
        (DATASET, invoices, "every case"),
        (TRAIN, train, "TUNE against this one"),
        (HOLDOUT, holdout, "DO NOT look at this until you think you are done"),
    ):
        _write(path, cases, note)

    print(f"\ninvoices: {len(invoices)} -> {INVOICE_DIR.name}/")
    print(f"  {TRAIN.name:32} {len(train):>4} cases   tune here")
    print(f"  {HOLDOUT.name:32} {len(holdout):>4} cases   score once, at the end")
    print(f"  {DATASET.name:32} {len(invoices):>4} cases   both together")
    print(
        f"\nA pass over the training set costs about {len(train) * 3} model calls:\n"
        f"  uv run python evals/run_decision_eval.py \\\n"
        f"    --dataset evals/{TRAIN.name} \\\n"
        f"    --policy evals/fixtures/corpus/procurement-policy.md"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
